#include "stm32f10x.h"                  // Device header
#include "PWM.h"

/**
  * 函    数：舵机初始化
  * 参    数：无
  * 返 回 值：无
  * @note    仅初始化底层PWM(TIM2时基与CH2通道); 舵机上电默认姿态由
  *          main.c的Servo_SetAngle(0)显式设定(关窗)
  */
void Servo_Init(void)
{
	PWM_Init();									//初始化舵机的底层PWM
}

/**
  * 函    数：舵机设置角度
  * 参    数：Angle 要设置的舵机角度，范围：0~180
  * 返 回 值：无
  * @note    线性映射公式: CCR = Angle/180 * 2000 + 500
  *          推导: 20ms周期=20000us(1us/计数), 0.5ms(500计数)对应0°,
  *          2.5ms(2500计数)对应180°, 线性内插即得上式;
  *          执行耗时<1µs(单寄存器写), PWM硬件自动维持脉宽
  */
void Servo_SetAngle(float Angle)
{
	PWM_SetCompare2(Angle / 180 * 2000 + 500);	//设置占空比
												//将角度线性变换，对应到舵机要求的占空比范围上
}

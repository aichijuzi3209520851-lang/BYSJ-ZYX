#include "stm32f10x.h"                  // Device header
#include "PWM.h"

/**
  * @brief  舵机初始化（初始化底层 TIM2 PWM）
  * @param  无
  * @retval 无
  * @note   调用上下文：main() 初始化阶段；之后必须调用一次 Servo_SetAngle(0)
  *          使天窗回到初始关闭位置（硬件上电后舵机角度未定义）
  */
void Servo_Init(void)
{
	PWM_Init();									//初始化舵机的底层PWM
}

/**
  * @brief  舵机设置角度
  * @param  Angle 目标角度，范围：0~180（单位：度）
  * @retval 无
  * @note   调用上下文：任务级（报警控制任务自动联动 / 通信任务手动指令），
  *          跨任务调用必须持有 xActuatorMutex（见 main.c）
  *
  *          脉宽换算公式（时基 1计数=1us，周期 20000us）：
  *            CCR = Angle / 180 * 2000 + 500
  *          即把 0~180° 线性映射到 500~2500us 脉宽：
  *            Angle=0   -> CCR=500  (0.5ms, 关窗)
  *            Angle=90  -> CCR=1500 (1.5ms, 中位)
  *            Angle=180 -> CCR=2500 (2.5ms, 开窗)
  */
void Servo_SetAngle(float Angle)
{
	PWM_SetCompare2(Angle / 180 * 2000 + 500);	//角度线性映射到舵机脉宽范围(见上方公式推导)
}
